(ns lcert.formal.ri-lemma36
  "Generic copy of lcert.formal.lemma36 over an R-interpretation ri : RInt (rint.clj;
  Theorem 4.6 design note §3), generated by formal/tools/gen_ri.py: the
  constants that depend on the model carry the suffix _ri and take ri after
  encTy.  Hand edits at the R-specific steps are marked `;; RI:`.  The
  standard namespace's documentation follows, with the same renaming.

  F3n — the fundamental lemma (R4-metatheory.md Lemma 3.6), assembled.

  lemma36_step: at a budget n, given the outer hypothesis OuterIH_ri n (Lemma
  3.6 at every smaller budget, for the all-token contexts Θₘ), every runtime
  derivation D ⊢ t :^us A in a well-formed context is sound:
      WFCtx D ⟹ Sound_ri n D us t A
  (for all η ⊨ₖ (D, us) with k ≤ n, ⟦t⟧ⁿη ∈ Vⁿₖ(A)η).  By induction on the
  derivation; each rule is its case lemma (fundamental.clj, outer.clj).  A
  premise under binders is used at the extended context, whose
  well-formedness the rule's formation premises give (WFCtx is a list of
  formation judgments, one per entry).

  outer_all: OuterIH_ri n for every n, by induction on n — OuterIH_ri (n+1) at
  m = n is lemma36_step_ri at n, at the token environment (tok_sat_ri).  This is
  §3.6's argument that the induction is not circular: a certificate is
  decoded at a budget strictly below the one being proved.

  lemma36: Sound_ri n D us t A for every n and every derivation in a
  well-formed context.

  Then Theorem 1 (consistency), Corollary 3.7 (Check accepts no refutation
  and no contradictory pair) and Theorem 3 (certificate size, and its
  refinement to the free tokens), from Lemma 3.6.

  One rule enters as a hypothesis until its case is proved: Conv (needs
  Lemma 3.2, conversion invariance), stated as exactly what the induction
  needs (ConvCase_ri)."
