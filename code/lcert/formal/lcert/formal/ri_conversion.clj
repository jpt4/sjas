(kdef EquivAt_ri
  (forall [chkf (=> Code Code Bool)] (forall [dec (=> Code (Option (Prod Nat (Prod Exp Exp))))] (forall [encTy (=> Exp Code) ri RInt]
    (=> Nat Bool (List Sk) Sk Exp Exp Prop))))
  (fn [chkf :- (=> Code Code Bool), dec :- (=> Code (Option (Prod Nat (Prod Exp Exp)))), encTy :- (=> Exp Code), ri :- RInt,
       n :- Nat, w :- Bool, G :- (List Sk), s :- Sk, a :- Exp, b :- Exp]
    (And (=> (Eq Bool w Bool.false)
             (And (forall [en (HEnv G)] (Eq (Car s) (den_ri chkf dec encTy ri n a G s en) (den_ri chkf dec encTy ri n b G s en)))
                  (Eq (Option Sk) (skOf G a) (skOf G b))))
         (=> (Eq Bool w Bool.true)
             (And (Eq Sk (skel a) (skel b))
                  (forall [en (HEnv G)] (forall [k Nat] (forall [v (Car (skel b))]
                    (Eq Prop (V_ri chkf dec encTy ri n a G en k (skel b) v) (V_ri chkf dec encTy ri n b G en k (skel b) v))))))))))

(def ^:private P4 '[chkf :- (=> Code Code Bool), dec :- (=> Code (Option (Prod Nat (Prod Exp Exp)))), encTy :- (=> Exp Code), ri :- RInt, n :- Nat])
(defn- dn [e G s en] (list 'den_ri 'chkf 'dec 'encTy 'ri 'n e G s en))
(defn- Vn [A G en k s v] (list 'V_ri 'chkf 'dec 'encTy 'ri 'n A G en k s v))
(defn- EQ [w G s a b] (list 'EquivAt_ri 'chkf 'dec 'encTy 'ri 'n w G s a b))
(defmacro ^:private pthm [nm params prop & tactics]
  `(a/prove-theorem '~nm (lv (into P4 '~params)) (lv '~prop) (lv '~(vec tactics))))

