(pthm mk_eqv_t_ri [w :- Bool, G :- (List Sk), s :- Sk, a :- Exp, b :- Exp, hw :- (Eq Bool w Bool.false),
                hd :- (forall [en (HEnv G)] (Eq (Car s) (den_ri chkf dec encTy ri n a G s en) (den_ri chkf dec encTy ri n b G s en))),
                hk :- (Eq (Option Sk) (skOf G a) (skOf G b))]
