(ns lcert.formal.ri-conversion
  "Generic copy of lcert.formal.conversion over an R-interpretation ri : RInt (rint.clj;
  Theorem 4.6 design note §3), generated by formal/tools/gen_ri.py: the
  constants that depend on the model carry the suffix _ri and take ri after
  encTy.  Hand edits at the R-specific steps are marked `;; RI:`.  The
  standard namespace's documentation follows, with the same renaming.

  F3m — conversion invariance (R4-metatheory.md §1.5, §3.2 Lemma 3.2,
  §3.3 Lemma 3.3's conversion clause) and the Conv case of the fundamental
  lemma (Lemma 3.6).

  The paper: if t ≡ t′ (both skeleton-typed) then ⟦t⟧ⁿη = ⟦t′⟧ⁿη
  (Lemma 3.2), and if A ≡ B then Vⁿₖ(A)η = Vⁿₖ(B)η (Lemma 3.3).  Conversion
  (conv.clj, Cv) is a chain of single steps (Step: a head step Hd at a
  path), taken in either direction, every element of which is a
  skeleton-well-formed type (SkJ Bool.true) satisfying nbr.

  DEVIATION (forced; conv_skj_counterexample_ri is the kernel-checked witness).  Over
  skeleton typing alone the conversion clause is FALSE for this
  denotation, for the reason substitution.clj §5 found for Lemma 3.1: a
  branch list (bnil / bcons) is skeleton-typed at Lbl → s, but skOf gives it
  no skeleton, so ⟦f u⟧ defaults when u is a branch list.  A β-step that
  moves a branch list out of argument position changes the denotation:
      b  = (λ(y : Π(l:Lbl).Bool). caseL Bool 0 y) (bcons tt bnil)
      b′ = caseL Bool 0 (bcons tt bnil)   (b ⇝ b′ by β)
  ⟦b⟧ = ff (the application defaults) but ⟦b′⟧ = tt, so the old Cv related T(b′) and T(b), both
  skeleton-well-formed, but V_ri(T b′) = {⋆} and V_ri(T b) = ∅.  The paper's
  syntax has no branch lists as terms (caseLbl's branches are part of its
  syntax); the encoding's bnil / bcons are first-class Exp terms only for
  structural recursion (syntax.clj).  Steps that read an argument through
  skOf (β, and the ι-steps that substitute or apply) therefore assume nbr
  (§1): a branch list may occur only as the branch list of a caseL, or as
  the tail of a branch list. Cv now requires nbr of each element,
  excluding this counterexample throughout a conversion chain.  Real (Rt/Tl) terms type branch lists only at the pseudo-type
  tBrs, which no binder or argument has.

  Contents.
  §1  skOf_complete (nbrF is defined in conv.clj): on a skeleton-typed term with no stray
      branch list, skOf returns the typed skeleton.
  §2  Inversion of skeleton typing (InvSkJ / skj_inv / inv_<ctor>).
  §3  EquivAt_ri, and the head steps proved so far (Lemma 3.2 for Hd).
      ι that only selects a branch (ite, elimB, recN at zero) and print
      preserve the denotation with no nbr hypothesis.  β preserves it
      when the redex is nbr (den_beta_ri, via den_subst1_ri and skOf_complete).
      conv_skj_counterexample_ri is the kernel-checked failure of β over
      SkJ alone.  itR on a leaf (den_itRL_nbr_ri) needs nbr so the label has an skOf.  T(tt) and T(ff) preserve V_ri (hd_tTT_ri, hd_tTF_ri).
  β for let (den_betaLet_ri) is the same pattern.  §4 proves the remaining head steps: recNS, recSL, recSN, caseLb, itR on a node, and δ (a canonical code term denotes its code, snode included).  §5 packages them: hd_den_ri is Lemma 3.2 at the root, and den_step_nil_ri is the empty-path case of position congruence.  A step under a constructor, the chain for V_ri, and F_conv_ri are not in this file yet.

  Equivalence at a position.  EquivAt_ri w G s a b says a may replace b at a
  position of mode w, context G and skeleton s:
    w = false (a term):  ⟦a⟧ G s η = ⟦b⟧ G s η for every η, and
