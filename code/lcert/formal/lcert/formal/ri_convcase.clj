    '(forall [l Nat] (forall [b Exp]
       (=> (Eq (Option Exp) (nthB bs l) (Option.some Exp b))
           (=> (SkJ Bool.false G bs (Sk.arr Sk.lbl outsk))
               (SkJ Bool.false G b outsk)))))
    (lv (into ['(induction bs)]
          (mapcat (fn [[idx [ctor fields]]]
