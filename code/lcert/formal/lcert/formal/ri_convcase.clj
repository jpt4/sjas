                          (SkJ Bool.false G b outsk)
                          (And.right hc)
                          (fn [s1 :- Sk, hs1 :- (And (Eq Sk (Sk.arr Sk.lbl outsk) (Sk.arr Sk.lbl s1))
                                                  (And (SkJ Bool.false G h s1)
                                                       (SkJ Bool.false G t (Sk.arr Sk.lbl s1))))]
